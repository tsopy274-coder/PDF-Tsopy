def translate_ts(ts_path: Path, translations: dict) -> int:
    tree = ET.parse(ts_path)
    root = tree.getroot()
    count = 0
    for msg in root.iter("message"):
        source = msg.find("source")
        trans = msg.find("translation")
        if source is None or trans is None:
            continue
        src_text = (source.text or "").strip()
        if src_text in translations:
            trans.text = translations[src_text]
            if "type" in trans.attrib:
                del trans.attrib["type"]
            count += 1
    tree.write(ts_path, encoding="utf-8", xml_declaration=True)
    return count

def main():
    if not TS_FILE.exists():
        print(f"Δεν βρέθηκε: {TS_FILE}")
        sys.exit(1)

    n = translate_ts(TS_FILE, TRANSLATIONS)
    print(f"Μεταφράστηκαν {n} μηνύματα στο {TS_FILE}")

    if LRELEASE.exists():
        print(f"Τρέχω lrelease...")
        subprocess.run([str(LRELEASE), str(TS_FILE), "-qm",
                        str(TS_FILE.with_suffix(".qm"))], check=True)
        print(f"Δημιουργήθηκε: {TS_FILE.with_suffix('.qm')}")
    else:
        print(f"⚠ Δεν βρέθηκε το lrelease: {LRELEASE}")

if __name__ == "__main__":
    main()